using System.Reflection;
using System.Text;
using Microsoft.AspNetCore.Components;
using Microsoft.FluentUI.AspNetCore.Components;

var repositoryRoot = Path.GetFullPath(Path.Combine(
    AppContext.BaseDirectory,
    "..",
    "..",
    "..",
    "..",
    ".."));
var outputDirectory = Path.Combine(
    repositoryRoot,
    "src",
    "A11yBlazor.Fluent",
    "Components",
    "Generated");

var types = typeof(FluentButton).Assembly
    .GetExportedTypes()
    .Where(type => type.Namespace == "Microsoft.FluentUI.AspNetCore.Components")
    .Where(type => typeof(IComponent).IsAssignableFrom(type))
    .Where(type => !type.IsAbstract && !type.IsInterface && type.IsClass)
    .Where(type => !type.IsNested)
    .OrderBy(type => type.Name)
    .ToArray();

var labelControls = new HashSet<string>(StringComparer.Ordinal)
{
    "FluentAutocomplete",
    "FluentCalendar",
    "FluentCheckbox",
    "FluentColorPickerInput",
    "FluentCombobox",
    "FluentDatePicker",
    "FluentListbox",
    "FluentNumberInput",
    "FluentRadioGroup",
    "FluentRadio",
    "FluentSelect",
    "FluentSlider",
    "FluentSwitch",
    "FluentTextArea",
    "FluentTextInput",
    "FluentTimePicker",
};

Directory.CreateDirectory(outputDirectory);
foreach (var generatedFile in Directory.EnumerateFiles(outputDirectory, "*.cs", SearchOption.TopDirectoryOnly))
{
    File.Delete(generatedFile);
}

var legacyOutputPath = Path.Combine(
    repositoryRoot,
    "src",
    "A11yBlazor.Fluent",
    "Components",
    "GeneratedAccessibleComponents.g.cs");
if (File.Exists(legacyOutputPath))
{
    File.Delete(legacyOutputPath);
}

foreach (var type in types)
{
    var text = new StringBuilder();
    text.AppendLine("// <auto-generated />");
    text.AppendLine("#nullable enable");
    text.AppendLine();
    text.AppendLine("using A11yBlazor.Fluent.Accessibility;");
    text.AppendLine("using Microsoft.AspNetCore.Components;");
    text.AppendLine("using Microsoft.AspNetCore.Components.Web;");
    text.AppendLine("using Microsoft.FluentUI.AspNetCore.Components;");
    text.AppendLine();
    text.AppendLine("namespace A11yBlazor.Fluent.Components;");
    text.AppendLine();

    var baseName = type.Name.Split('`')[0];
    var genericParameters = type.GetGenericArguments();
    var genericText = genericParameters.Length == 0
        ? string.Empty
        : $"<{string.Join(", ", genericParameters.Select(parameter => parameter.Name))}>";
    var wrapperName = $"A11y{baseName}{genericText}";
    var hasAdditionalAttributes = GetProperty(type, "AdditionalAttributes") is not null;
    var loadingProperty = GetProperty(type, "Loading");
    var labelProperty = GetProperty(type, "Label");
    var needsVisibleLabel = labelControls.Contains(baseName) && labelProperty is not null;
    var isImage = baseName == "FluentImage";
    var isDecorativeIcon = baseName is "FluentIcon" or "FluentEmoji";
    var autoCompleteProperty = GetProperty(type, "AutoComplete");

    text.AppendLine("/// <summary>");
    text.AppendLine($"/// Fluent UI の {baseName} を継承し、アクセシビリティ契約を適用するコンポーネントです。");
    text.AppendLine("/// </summary>");
    text.AppendLine($"public class {wrapperName} : {FormatType(type)}");

    foreach (var parameter in genericParameters)
    {
        var constraints = FormatConstraints(parameter);
        if (constraints.Count > 0)
        {
            text.AppendLine($"    where {parameter.Name} : {string.Join(", ", constraints)}");
        }
    }

    text.AppendLine("{");
    foreach (var constructor in type.GetConstructors(BindingFlags.Instance | BindingFlags.Public))
    {
        var parameters = constructor.GetParameters();
        if (parameters.Length == 0)
        {
            continue;
        }

        var signature = string.Join(
            ", ",
            parameters.Select(parameter => $"{FormatType(parameter.ParameterType)} {parameter.Name}"));
        var arguments = string.Join(", ", parameters.Select(parameter => parameter.Name));
        text.AppendLine("    /// <summary>");
        text.AppendLine("    /// Fluent UI の依存関係を継承してコンポーネントを初期化します。");
        text.AppendLine("    /// </summary>");
        foreach (var parameter in parameters)
        {
            text.AppendLine($"    /// <param name=\"{parameter.Name}\">継承元の構成に渡す値です。</param>");
        }
        text.AppendLine($"    public A11y{baseName}({signature}) : base({arguments})");
        text.AppendLine("    {");
        text.AppendLine("    }");
        text.AppendLine();
    }

    text.AppendLine("    /// <summary>");
    text.AppendLine("    /// コンポーネント契約の検証器を取得または設定します。");
    text.AppendLine("    /// </summary>");
    text.AppendLine("    [Inject]");
    text.AppendLine("    public IAccessibilityValidator AccessibilityValidator { get; set; } = default!;");
    text.AppendLine();

    if (hasAdditionalAttributes)
    {
        AppendParameter(
            text,
            "string?",
            "AccessibleName",
            "支援技術へ公開するアクセシブルな名前を取得または設定します。");
        AppendParameter(
            text,
            "string?",
            "AccessibleDescription",
            "支援技術へ公開する追加説明を取得または設定します。");
        AppendParameter(
            text,
            "string?",
            "NewWindowDescription",
            "Target が新しい閲覧コンテキストを開く場合の事前説明を取得または設定します。");
        AppendParameter(
            text,
            "EventCallback<KeyboardEventArgs>",
            "OnKeyboardActivate",
            "クリック操作と同等の Enter または Space 操作を受け取るコールバックを取得または設定します。");
        AppendParameter(
            text,
            "EventCallback<KeyboardEventArgs>",
            "OnKeyboardAlternative",
            "ドラッグまたは並べ替えと同等のキーボード操作を受け取るコールバックを取得または設定します。");
        if (autoCompleteProperty is not null)
        {
            AppendParameter(
                text,
                "bool",
                "RepresentsPersonalData",
                "入力値が利用者自身に関する個人データを表すかどうかを取得または設定します。");
        }
    }

    if (loadingProperty is not null)
    {
        AppendParameter(
            text,
            "string?",
            "LoadingLabel",
            "読み込み中であることを示す状態名を取得または設定します。");
    }

    if (isImage || isDecorativeIcon)
    {
        var defaultValue = isDecorativeIcon ? " = true;" : " = false;";
        text.AppendLine("    /// <summary>");
        text.AppendLine(isImage
            ? "    /// 画像が純粋な装飾であり代替テキストを不要とするかどうかを取得または設定します。"
            : "    /// アイコンが純粋な装飾であり支援技術から隠すかどうかを取得または設定します。");
        text.AppendLine("    /// </summary>");
        text.AppendLine("    [Parameter]");
        text.AppendLine($"    public bool Decorative {{ get; set; }}{defaultValue}");
        text.AppendLine();
    }

    if (needsVisibleLabel)
    {
        text.AppendLine("    /// <summary>");
        text.AppendLine("    /// 入力欄に対応する必須の可視ラベルを取得または設定します。");
        text.AppendLine("    /// </summary>");
        text.AppendLine("    [Parameter, EditorRequired]");
        text.AppendLine("    public new string? Label { get; set; }");
        text.AppendLine();
    }

    if (isImage)
    {
        text.AppendLine("    /// <summary>");
        text.AppendLine("    /// 情報を持つ画像の代替テキストを取得または設定します。装飾画像では不要です。");
        text.AppendLine("    /// </summary>");
        text.AppendLine("    [Parameter]");
        text.AppendLine("    public new string? AlternateText { get; set; }");
        text.AppendLine();
    }

    text.AppendLine("    /// <summary>");
    text.AppendLine("    /// パラメーター設定後にアクセシビリティ属性を適用し、契約を検証します。");
    text.AppendLine("    /// </summary>");
    text.AppendLine("    protected override void OnParametersSet()");
    text.AppendLine("    {");
    text.AppendLine("        base.OnParametersSet();");

    if (needsVisibleLabel)
    {
        text.AppendLine("        base.Label = Label;");
    }

    if (isImage)
    {
        text.AppendLine("        base.AlternateText = Decorative ? string.Empty : AlternateText;");
    }

    if (hasAdditionalAttributes)
    {
        text.AppendLine("        AdditionalAttributes = AccessibilityAttributeHelper.Merge(this);");
    }

    if (isImage)
    {
        text.AppendLine("        if (Decorative)");
        text.AppendLine("        {");
        text.AppendLine("                    AlternateText = string.Empty;");
        text.AppendLine("        }");
    }

    text.AppendLine("        AccessibilityValidator.Validate(this);");
    text.AppendLine("    }");
    text.AppendLine("}");
    File.WriteAllText(
        Path.Combine(outputDirectory, $"A11y{baseName}.g.cs"),
        text.ToString(),
        new UTF8Encoding(false));
}

