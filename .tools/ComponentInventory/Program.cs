/// <summary>
/// Razor コンポーネントの公開パラメーター宣言を生成します。
/// </summary>
/// <param name="text">出力先の文字列バッファーです。</param>
/// <param name="type">パラメーターの型名です。</param>
/// <param name="name">パラメーター名です。</param>
/// <param name="description">日本語の XML ドキュメントです。</param>
static void AppendParameter(StringBuilder text, string type, string name, string description)
{
    text.AppendLine("    /// <summary>");
    text.AppendLine($"    /// {description}");
    text.AppendLine("    /// </summary>");
    text.AppendLine("    [Parameter]");
    text.AppendLine($"    public {type} {name} {{ get; set; }}");
    text.AppendLine();
}

/// <summary>
/// 指定した名前の公開インスタンスプロパティを取得します。
/// </summary>
/// <param name="type">検索対象の型です。</param>
/// <param name="name">プロパティ名です。</param>
/// <returns>存在する場合はプロパティ情報です。</returns>
static PropertyInfo? GetProperty(Type type, string name)
{
    return type.GetProperty(name, BindingFlags.Instance | BindingFlags.Public);
}

/// <summary>
/// Reflection の型を C# の完全修飾型名へ変換します。
/// </summary>
/// <param name="type">変換対象の型です。</param>
/// <returns>ソースコードに使用できる型名です。</returns>
static string FormatType(Type type)
{
    if (type.IsGenericParameter)
    {
        return type.Name;
    }

    if (!type.IsGenericType)
    {
        return type.FullName ?? type.Name;
    }

    var definition = type.GetGenericTypeDefinition();
    var name = (definition.FullName ?? definition.Name).Split('`')[0];
    return $"{name}<{string.Join(", ", type.GetGenericArguments().Select(FormatType))}>";
}

/// <summary>
/// ジェネリックパラメーターの制約を C# の宣言へ変換します。
/// </summary>
/// <param name="parameter">変換対象のジェネリックパラメーターです。</param>
/// <returns>制約の一覧です。</returns>
static List<string> FormatConstraints(Type parameter)
{
    var constraints = new List<string>();
    var attributes = parameter.GenericParameterAttributes;

    if ((attributes & GenericParameterAttributes.ReferenceTypeConstraint) != 0)
    {
        constraints.Add("class");
    }
    else if ((attributes & GenericParameterAttributes.NotNullableValueTypeConstraint) != 0)
    {
        constraints.Add("struct");
    }

    foreach (var constraint in parameter.GetGenericParameterConstraints())
    {
        if (constraint != typeof(ValueType))
        {
            constraints.Add(FormatType(constraint));
        }
    }

    if ((attributes & GenericParameterAttributes.DefaultConstructorConstraint) != 0 &&
        (attributes & GenericParameterAttributes.NotNullableValueTypeConstraint) == 0)
    {
        constraints.Add("new()");
    }

    if (attributes.HasFlag(GenericParameterAttributes.DefaultConstructorConstraint) &&
        constraints.Count == 0)
    {
        constraints.Add("new()");
    }

    return constraints;
}

/// <summary>
/// 全公開コンポーネントの利用時必須項目と状態別契約を Markdown に生成します。
/// </summary>
/// <param name="repositoryRoot">リポジトリのルートです。</param>
/// <param name="types">対象となる Fluent UI コンポーネント型です。</param>
/// <param name="labelControls">可視ラベルが必須のコンポーネント名です。</param>
static void WriteContractCatalog(
    string repositoryRoot,
    IReadOnlyList<Type> types,
    HashSet<string> labelControls)
{
    var catalog = new StringBuilder();
    catalog.AppendLine("# コンポーネント別アクセシビリティ契約");
    catalog.AppendLine();
    catalog.AppendLine("この表は Fluent UI Blazor の公開型メタデータから自動生成されます。");
    catalog.AppendLine("Razor の `EditorRequired`、実行時検証、継承元が公開する状態属性を区別して記載します。");
    catalog.AppendLine();
    catalog.AppendLine("| A11y コンポーネント | 利用時に必須 | 状態別の契約 |");
    catalog.AppendLine("|---|---|---|");

    foreach (var type in types)
    {
        var name = type.Name.Split('`')[0];
        var wrapperName = $"A11y{name}";
        var requirements = new List<string>();
        var states = new List<string>();
        var properties = type
            .GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(property => property.IsDefined(typeof(ParameterAttribute), true))
            .Select(property => property.Name)
            .ToHashSet(StringComparer.Ordinal);

        if (labelControls.Contains(name))
        {
            requirements.Add("`Label`（EditorRequired）");
        }

        if (name == "FluentImage")
        {
            requirements.Add("情報画像は `AlternateText`、装飾画像は `Decorative=true`");
        }

        if (name is "FluentButton" or "FluentAnchorButton" or "FluentCompoundButton" or
            "FluentMenuButton" or "FluentSplitButton" or "FluentToggleButton")
        {
            states.Add("アイコンのみ／子なし: `AccessibleName`");
        }

        if (name is "FluentIcon" or "FluentEmoji")
        {
            states.Add("意味を持つアイコン: `Decorative=false` と `AccessibleName`");
            states.Add("クリック可能: 装飾不可、キーボード代替が必要");
        }

        if (name is "FluentInputFile" or "FluentTabs" or "FluentSpinner" or
            "FluentProgress" or "FluentProgressBar" or "FluentProgressRing")
        {
            requirements.Add("`AccessibleName`");
        }

        if (name == "FluentDataGrid")
        {
            requirements.Add("`AccessibleName`");
        }

        if (name == "FluentDialogBody")
        {
            requirements.Add("`TitleTemplate` または `AccessibleName`");
        }

        if (name == "FluentTooltip")
        {
            requirements.Add("`Anchor` と説明内容");
        }

        if (properties.Contains("MessageState"))
        {
            states.Add("エラー: `Message` または `MessageTemplate`");
        }

        if (properties.Contains("Target"))
        {
            states.Add("新しいタブ／ウィンドウ: `NewWindowDescription`");
        }

        if (properties.Contains("AutoComplete"))
        {
            states.Add("本人データ: `RepresentsPersonalData=true` と対応する `AutoComplete`");
        }

        if (properties.Contains("Autofocus"))
        {
            states.Add("自動フォーカス: 画面遷移時の目的を画面単位で確認");
        }

        if (properties.Contains("DisabledFocusable"))
        {
            states.Add("フォーカス可能な無効状態: 無効理由を `AccessibleDescription` で説明");
        }

        if (properties.Contains("MaskPattern") ||
            properties.Contains("Pattern") ||
            properties.Contains("Min") ||
            properties.Contains("Max") ||
            properties.Contains("MinLength") ||
            properties.Contains("MaxLength") ||
            properties.Contains("MinDate") ||
            properties.Contains("MaxDate"))
        {
            states.Add("書式・範囲制約: `AccessibleDescription`");
        }

        if (properties.Contains("Multiple") || name == "FluentInputFile")
        {
            states.Add("複数選択・ファイル制限: `AccessibleDescription`");
        }

        if (name is "FluentAvatar" or "FluentCard" or "FluentIcon" or "FluentEmoji")
        {
            states.Add("`OnClick` 使用: `AccessibleName` と `OnKeyboardActivate`");
        }

        if (properties.Contains("Draggable") ||
            properties.Contains("Droppable") ||
            properties.Contains("ReorderableColumns") ||
            name is "FluentDragContainer" or "FluentDropZone" or "FluentSortableList")
        {
            states.Add("ドラッグ・並べ替え: `OnKeyboardAlternative`");
        }

        if (name == "FluentAvatar")
        {
            states.Add("画像表示: `Name`");
        }

        if (name is "FluentBadge" or "FluentCounterBadge")
        {
            states.Add("アイコンのみ: `IconLabel` または `AccessibleName`");
        }

        if (name == "FluentColorPicker")
        {
            requirements.Add("`AccessibleName`");
        }

        if (properties.Contains("Loading"))
        {
            states.Add("読み込み中: `LoadingLabel`");
        }

        if (properties.Contains("Required"))
        {
            states.Add("必須: 基底コンポーネントの必須属性を保持");
        }

        if (properties.Contains("Disabled"))
        {
            states.Add("無効: 操作停止と利用可能理由を画面文脈で提示");
        }

        if (properties.Contains("ReadOnly"))
        {
            states.Add("読み取り専用: 値を読め、操作できないことを保持");
        }

        if (properties.Contains("Expanded"))
        {
            states.Add("展開／折りたたみ: 基底の `aria-expanded` を保持");
        }

        if (properties.Contains("Checked") || properties.Contains("CheckState"))
        {
            states.Add("選択: 基底の選択状態と変更通知を保持");
        }

        if (requirements.Count == 0)
        {
            requirements.Add("なし（Fluent UI の既定契約を継承）");
        }

        if (states.Count == 0)
        {
            states.Add("基底コンポーネントの名前・役割・値とキーボード操作を画面単位で確認");
        }

        catalog.AppendLine(
            $"| `{wrapperName}` | {string.Join("<br>", requirements)} | {string.Join("<br>", states)} |");
    }

    var docsPath = Path.Combine(repositoryRoot, "docs");
    Directory.CreateDirectory(docsPath);
    File.WriteAllText(
        Path.Combine(docsPath, "component-contracts.md"),
        catalog.ToString(),
        new UTF8Encoding(false));
}
